#!/bin/bash
# install.sh — One-command setup for hermes-muse-bridge.
#
# Interactive and idempotent: safe to re-run. It will:
#   1. Ask for transport mode, box host, and optional Telegram config
#   2. Generate config.yaml from your answers
#   3. Deploy the kanban daemon to the Hermes box
#   4. Set up @reboot cron on the box
#   5. Install Muse VM scripts (listener, tunnel, watcher)
#   6. Start the listener and tunnel
#   7. Deploy skills
#   8. Print verification steps
#
# Usage:
#   ./install.sh [--help] [--dry-run] [--config PATH]
#
#   --dry-run: print what would be done without doing it
#   --config:  use an existing config.yaml instead of asking

set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG_FILE="$REPO_DIR/config.yaml"
DRY_RUN=0

if [ "${1:-}" = "--help" ]; then
  sed -n '2,/^set -euo/p' "$0" | sed 's/^# //; s/^#//'
  exit 0
fi
if [ "${1:-}" = "--dry-run" ]; then
  DRY_RUN=1
  echo "DRY RUN — no changes will be made"
  echo ""
fi
if [ "${1:-}" = "--config" ] && [ -n "${2:-}" ]; then
  CONFIG_FILE="$2"
fi

run() {
  if [ "$DRY_RUN" = "1" ]; then
    echo "  [dry-run] $*"
  else
    "$@"
  fi
}

ask() { # $1=prompt, $2=default
  local answer
  read -rp "$1 [$2]: " answer
  echo "${answer:-$2}"
}

# ── Step 1: Gather config ──

echo "=== hermes-muse-bridge installer ==="
echo ""

if [ -f "$CONFIG_FILE" ] && [ "$DRY_RUN" = "0" ]; then
  echo "Found existing $CONFIG_FILE"
  REUSE=$(ask "Reuse it? (y/n)" "y")
  if [ "$REUSE" != "y" ]; then
    rm -f "$CONFIG_FILE"
  fi
fi

if [ ! -f "$CONFIG_FILE" ]; then
  if [ "$DRY_RUN" = "1" ]; then
    # Dry-run: use defaults, no prompts
    TRANSPORT="tailscale-ssh"
    BOX_HOST="box.example.com"
    BOX_USER="ubuntu"
    ASSIGNEE="muse"
    echo "(dry-run: using defaults, no prompts)"
  else
    echo "Transport mode:"
  echo "  1) tailscale-ssh — box and VM on the same Tailscale tailnet"
  echo "  2) direct-ssh    — box reachable directly (LAN IP or hostname)"
  echo "  3) localhost     — both on the same machine"
  TRANSPORT_CHOICE=$(ask "Choose (1/2/3)" "1")
  case "$TRANSPORT_CHOICE" in
    1) TRANSPORT="tailscale-ssh" ;;
    2) TRANSPORT="direct-ssh" ;;
    3) TRANSPORT="localhost" ;;
    *) TRANSPORT="tailscale-ssh" ;;
  esac

  if [ "$TRANSPORT" != "localhost" ]; then
    BOX_HOST=$(ask "Hermes box hostname or IP" "")
    BOX_USER=$(ask "SSH user" "ubuntu")
  else
    BOX_HOST="localhost"
    BOX_USER="$USER"
  fi

  echo ""
  echo "Telegram notifications (optional — leave blank to skip):"
  TG_TOKEN=$(ask "Bot token (from @BotFather)" "")
  TG_CHAT=$(ask "Chat ID for notifications" "")

  ASSIGNEE=$(ask "Kanban assignee for Muse" "muse")

  # Write config.yaml
  if [ "$DRY_RUN" = "0" ]; then
    cat > "$CONFIG_FILE" << EOF
# Generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
transport: $TRANSPORT
box:
  host: "$BOX_HOST"
  user: "$BOX_USER"
  hermes_home: "/home/$BOX_USER/.hermes"
muse_vm:
  listener_port: 8899
  tunnel_remote_port: 18989
  watch_interval: "1m"
kanban:
  assignee: "$ASSIGNEE"
  max_claims_per_run: 5
  max_concurrent_agents: 3
  retry_grace_minutes: 30
  max_retries: 3
EOF
    if [ -n "$TG_TOKEN" ]; then
      cat >> "$CONFIG_FILE" << EOF
telegram:
  env_file: "~/.hermes/profiles/notifications/.env"
  notify_kinds: [completed, blocked, crashed, failed, gave_up]
EOF
    fi
    chmod 600 "$CONFIG_FILE"
    echo ""
    echo "Wrote $CONFIG_FILE"
  fi
  fi  # end dry-run else
else
  # Read from existing config (minimal parse)
  TRANSPORT=$(grep "^transport:" "$CONFIG_FILE" | awk '{print $2}')
  BOX_HOST=$(grep -A2 "^box:" "$CONFIG_FILE" | grep "host:" | awk '{print $2}' | tr -d '"')
  BOX_USER=$(grep -A2 "^box:" "$CONFIG_FILE" | grep "user:" | awk '{print $2}' | tr -d '"')
  ASSIGNEE=$(grep -A6 "^kanban:" "$CONFIG_FILE" | grep "assignee:" | awk '{print $2}' | tr -d '"')
  TRANSPORT="${TRANSPORT:-tailscale-ssh}"
  BOX_HOST="${BOX_HOST:-localhost}"
  BOX_USER="${BOX_USER:-ubuntu}"
  ASSIGNEE="${ASSIGNEE:-muse}"
fi

BOX_HOME="/home/$BOX_USER/.hermes"
echo ""
echo "Config: transport=$TRANSPORT box=$BOX_USER@$BOX_HOST assignee=$ASSIGNEE"
echo ""

# ── Step 2: Deploy box daemon ──

echo "=== Deploying kanban daemon to box ==="

ssh_cmd() {
  if [ "$TRANSPORT" = "localhost" ]; then
    eval "$1"
  else
    ssh -o BatchMode=yes -o ConnectTimeout=15 -o StrictHostKeyChecking=no \
        -o UserKnownHostsFile=/dev/null "$BOX_USER@$BOX_HOST" "$1"
  fi
}

# Copy daemon
if [ "$TRANSPORT" = "localhost" ]; then
  run mkdir -p "$BOX_HOME/bin"
  run cp "$REPO_DIR/box/kanban-events-daemon.py" "$BOX_HOME/bin/"
  run chmod +x "$BOX_HOME/bin/kanban-events-daemon.py"
else
  run ssh_cmd "mkdir -p $BOX_HOME/bin"
  # Use base64 for reliable transfer
  B64=$(base64 -w0 "$REPO_DIR/box/kanban-events-daemon.py")
  if [ "$DRY_RUN" = "0" ]; then
    ssh_cmd "echo '$B64' | base64 -d > $BOX_HOME/bin/kanban-events-daemon.py && chmod +x $BOX_HOME/bin/kanban-events-daemon.py"
  else
    echo "  [dry-run] upload kanban-events-daemon.py to box"
  fi
fi

# Write bridge config on box
if [ "$DRY_RUN" = "0" ]; then
  if [ "$TRANSPORT" = "localhost" ]; then
    cp "$CONFIG_FILE" "$BOX_HOME/bridge-config.yaml"
  else
    B64=$(base64 -w0 "$CONFIG_FILE")
    ssh_cmd "echo '$B64' | base64 -d > $BOX_HOME/bridge-config.yaml && chmod 600 $BOX_HOME/bridge-config.yaml"
  fi
else
  echo "  [dry-run] upload config.yaml to box as bridge-config.yaml"
fi

# @reboot cron (idempotent: remove old, add new)
echo "Setting up @reboot cron on box..."
if [ "$DRY_RUN" = "0" ]; then
  ssh_cmd "(crontab -l 2>/dev/null | grep -v 'kanban-events-daemon.py'; echo '@reboot /usr/bin/python3 $BOX_HOME/bin/kanban-events-daemon.py >> $BOX_HOME/logs/kanban-events-daemon.log 2>&1') | crontab -"
else
  echo "  [dry-run] update @reboot cron on box"
fi

# Start daemon now (kill old instance first)
echo "Starting daemon..."
if [ "$DRY_RUN" = "0" ]; then
  ssh_cmd "pkill -f kanban-events-daemon.py 2>/dev/null; sleep 1; nohup /usr/bin/python3 $BOX_HOME/bin/kanban-events-daemon.py >> $BOX_HOME/logs/kanban-events-daemon.log 2>&1 & echo started"
else
  echo "  [dry-run] restart kanban-events-daemon.py on box"
fi

# ── Step 3: Install Muse VM scripts ──

echo ""
echo "=== Installing Muse VM scripts ==="
BIN_DIR="$HOME/workspace/bin"
run mkdir -p "$BIN_DIR"
run cp "$REPO_DIR/muse-vm/inbox-listener.py" "$BIN_DIR/"
run cp "$REPO_DIR/muse-vm/tunnel.sh" "$BIN_DIR/"
run cp "$REPO_DIR/muse-vm/inbox-watch.sh" "$BIN_DIR/"
run chmod +x "$BIN_DIR/inbox-listener.py" "$BIN_DIR/tunnel.sh" "$BIN_DIR/inbox-watch.sh"

# Write env file for scripts
ENV_FILE="$BIN_DIR/bridge-env.sh"
if [ "$DRY_RUN" = "0" ]; then
  cat > "$ENV_FILE" << EOF
# Generated by hermes-muse-bridge install.sh — do not edit manually
export BRIDGE_TRANSPORT="$TRANSPORT"
export BRIDGE_BOX_HOST="$BOX_HOST"
export BRIDGE_BOX_USER="$BOX_USER"
export BRIDGE_BOX_HOME="$BOX_HOME"
export BRIDGE_ASSIGNEE="$ASSIGNEE"
export BRIDGE_SSH_CMD="ssh -o BatchMode=yes -o ConnectTimeout=15 -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null $BOX_USER@$BOX_HOST"
EOF
  chmod 600 "$ENV_FILE"
  echo "Wrote $ENV_FILE"
else
  echo "  [dry-run] write $ENV_FILE"
fi

# ── Step 4: Start listener and tunnel ──

echo ""
echo "=== Starting listener and tunnel ==="
if [ "$DRY_RUN" = "0" ]; then
  # Listener
  if curl -s -m 3 http://127.0.0.1:8899/health 2>/dev/null | grep -q '"ok"'; then
    echo "Listener already running"
  else
    # shellcheck disable=SC1091
    source "$ENV_FILE"
    nohup python3 "$BIN_DIR/inbox-listener.py" >/dev/null 2>&1 &
    sleep 2
    echo "Listener started"
  fi
  # Tunnel (skip for localhost)
  if [ "$TRANSPORT" != "localhost" ]; then
    if pgrep -f "muse-tunnel.sh" >/dev/null; then
      echo "Tunnel already running"
    else
      # shellcheck disable=SC1091
      source "$ENV_FILE"
      nohup "$BIN_DIR/tunnel.sh" >/dev/null 2>&1 &
      echo "Tunnel started"
    fi
  else
    echo "Localhost transport — no tunnel needed"
  fi
else
  echo "  [dry-run] start listener and tunnel"
fi

# ── Step 5: Deploy skills ──

echo ""
echo "=== Deploying skills ==="
run mkdir -p "$HOME/workspace/custom-skills"
run cp -r "$REPO_DIR/skills/muse-kanban-worker" "$HOME/workspace/custom-skills/"
echo "Deployed muse-kanban-worker skill to Muse VM"

if [ "$TRANSPORT" = "localhost" ]; then
  for profile_dir in "$BOX_HOME"/profiles/*/; do
    profile=$(basename "$profile_dir")
    run mkdir -p "$profile_dir/skills/call-muse"
    run cp "$REPO_DIR/skills/call-muse/SKILL.md" "$profile_dir/skills/call-muse/"
  done
  echo "Deployed call-muse skill to all Hermes profiles"
else
  echo "To deploy the call-muse skill to Hermes profiles, run on the box:"
  echo "  for p in $BOX_HOME/profiles/*/; do"
  echo "    mkdir -p \"\$p/skills/call-muse\""
  echo "    cp <repo>/skills/call-muse/SKILL.md \"\$p/skills/call-muse/\""
  echo "  done"
fi

# ── Step 6: Verification ──

echo ""
echo "=== Verification ==="
if [ "$DRY_RUN" = "0" ]; then
  echo "Health check:"
  curl -s --max-time 10 http://127.0.0.1:8899/health/detailed 2>/dev/null | python3 -m json.tool 2>/dev/null || echo "  (listener not responding yet — check ~/workspace/inbox/listener.log)"
  echo ""
  echo "Test with a kanban task:"
  echo "  On the box: hermes kanban create \"Test task\" --assignee $ASSIGNEE"
  echo "  Within ~1 minute, Muse should claim it."
else
  echo "  [dry-run] skip verification"
fi

echo ""
echo "Done! See TROUBLESHOOTING.md if anything isn't working."
